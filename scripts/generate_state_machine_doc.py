def render_table(policy: dict) -> str:
    lines = front_matter("Lifecycle Table", 1, "/state-machine/table/", parent=True)
    states = len(lc.LIFECYCLE)
    rows = sum(len(s.transitions) for s in lc.LIFECYCLE.values())
    rule_rows = sum(1 for e in lc.table_edges() if lc.is_rule_row(e))
    verbs = len({e.verb for e in lc.table_edges()})
    operation_rows = sum(len(s.transitions) for s in lc.OPERATIONS.values())
    lines += [
        "# Lifecycle table", "{: .no_toc }", "",
        "This is the contribution state machine as defined in `lifecycle.py`: "
        f"{states} states, {rows} transitions with {verbs} distinct verbs ({rule_rows} of the "
        f"transitions are expanded from {len(lc.RULES)} rules), {len(lc.FLAGS)} "
        f"flag{'s' if len(lc.FLAGS) != 1 else ''}, "
        f"and {len(lc.BUDGETS)} retry budgets, plus the operation table with "
        f"{len(lc.OPERATIONS)} states and {operation_rows} transitions. A contribution starts in "
        f"`{lc.INITIAL_STATE}` (`{lc.INITIAL_VERB}`).", "",
        "A requested task is identified by its " + ", ".join(lc.WORK_IDENTITY[:-1])
        + f", and {lc.WORK_IDENTITY[-1]}. A Result that differs in any of them is never folded "
        "and never published.", "",
    ]
    lines += toc()
    lines += ["## Triggers", "", "| Trigger | Meaning |", "|:--------|:--------|"]
    lines += [f"| `{k}` | {cell(v)} |" for k, v in lc.TRIGGER_DESCRIPTIONS.items()]
    lines += ["", "## State kinds", "", "| Kind | Meaning |", "|:-----|:--------|"]
    lines += [f"| `{k}` | {cell(v)} |" for k, v in lc.KIND_DESCRIPTIONS.items()]
    lines += ["", "## States", "",
              "*Launches* means the controller may allocate a task or launch remote effects from the "
              "state, subject to the flags. *Fork writes* means automated writers may write the "
              "contribution fork. *Exits* counts the state's own transitions and, after the plus "
              "sign, the rule transitions that apply in it.", "",
              "| State | Kind | Launches | Fork writes | Exits | Description |",
              "|:------|:-----|:---------|:------------|:------|:------------|"]
    for key, s in lc.LIFECYCLE.items():
        ruled = sum(1 for e in lc.state_edges(key) if lc.is_rule_row(e))
        lines.append(f"| `{key}` | `{s.kind}` | {'yes' if s.launches else 'no'} | "
                     f"{'yes' if s.writes else 'no'} | {len(s.transitions) - ruled} + {ruled} | "
                     f"{cell(s.description)} |")
    lines += ["", "## State invariants", "",
              "Every record in a state satisfies the invariants the state requires. `lifecycle "
              "check` proves that no row enters a state without them: each requirement of the "
              "target is kept from the source, implied by a guard of the row, established by its "
              "effects, or (`not_paused`) assured by the mask of the flag. The engine refuses a "
              "row from a record that breaks its state (`source_invalid`), but for the stops, a "
              "late Result and the row that heals the invariant, and a row whose record after it "
              "breaks its target (`target_invalid`).", "",
              "| Invariant | Meaning | Implied by | Healed by |",
              "|:----------|:--------|:-----------|:----------|"]
    for name, inv in lc.INVARIANTS.items():
        implied = "; ".join(g for g, names in lc.IMPLIES.items() if name in names)
        lines.append(f"| `{name}` | {cell(inv.description)} | {cell(implied) or '-'} | "
                     f"{', '.join(f'`{v}`' for v in inv.heal) if inv.heal else 'the stop after a processing error'} |")
    lines += ["", "| State | Requires |", "|:------|:---------|"]
    lines += [f"| `{key}` | {code(s.requires)} |" for key, s in lc.LIFECYCLE.items()]
    lines += ["", "## Partial clears", "",
              "An effect normally clears a whole field. These entries clear a part of one.", "",
              "| Entry | Field | What is cleared |", "|:------|:------|:----------------|"]
    lines += [f"| `{entry}` | `{name}` | {cell(meaning)} |"
              for entry, (name, meaning) in lc.QUALIFIED_CLEARS.items()]
    lines += ["", "## Rules", "",
              "A rule is a transition that applies in many states. It is written once and "
              "expanded into one row per state; the rows appear under each state below, marked "
              "*(rule)*.", ""]
    for verb, rule in lc.RULES.items():
        to = "same state" if rule.target == lc.SELF else f"`{rule.target}`"
        lines += [f"### `{verb}`", f"{{: #rule-{verb} }}", "", f"Applies in {rule.applies}.", ""]
        lines += TRANSITION_HEADER + [transition_row(verb, to, rule.transition), "",
                                      f"Expanded into: {code(lc.rule_states(verb))}.", ""]
    lines += ["## Flags", "",
              "A flag is stored beside the state. It is set and cleared from every non-terminal "
              "state and keeps phase and activity, except where noted.", ""]
    for name, f in lc.FLAGS.items():
        lines += [f"### `{name}`", f"{{: #flag-{name} }}", "", f"Stored in `{f.field}`. {f.description}", "",
                  "| Verb | Sets or clears | Trigger | Guard | Effects |",
                  "|:-----|:---------------|:--------|:------|:--------|"]
        for what, verbs_ in (("sets", f.set_by), ("clears", f.cleared_by)):
            for verb, t in verbs_.items():
                guard = "; ".join(t.guard) + (f". {t.description}" if t.description else "")
                lines.append(f"| `{verb}` | {what} | {trigger_text(t)} | {cell(guard)} | "
                             f"{effects_text(t.effects)} |")
        if f.set_moves:
            lines += ["", "Setting the flag clears the requested task, so these states are left "
                          "for the state in which that task is due again:", "",
                      "| From | To |", "|:-----|:---|"]
            lines += [f"| `{source}` | `{target}` |" for source, target in f.set_moves.items()]
        lines += ["", "While set:", "", "| Trigger | Effect |", "|:--------|:-------|"]
        lines += [f"| `{k}` | {cell(v)} |" for k, v in f.mask.items()]
        lines.append("")
    lines += ["## Transitions", "",
              "For each state, the verbs available from it. A verb leads from a state to one "
              "target only. *Same state* means the transition keeps phase and activity.", ""]
    for key, state in lc.LIFECYCLE.items():
        lines += [f"### `{key}`", f"{{: #state-{key.replace('.', '-')} }}", ""]
        if state.kind == "terminal":
            lines += ["Terminal: no transition leaves this state.", ""]
        lines += TRANSITION_HEADER
        for e in lc.state_edges(key):
            to = "same state" if e.target == key else f"`{e.target}`"
            lines.append(transition_row(e.verb, to, e.transition, rule=lc.is_rule_row(e)))
        lines.append("")
    lines += ["## Budgets", "",
              "Each budget counts charges by the verbs that name it. Its limit is a `policy.json` "
              "value, plus one when the first try is free. When the count reaches the limit, an "
              "exhaustion verb is taken instead. Exhaustion of an infrastructure budget always "
              "leads to a human wait of the same phase. Every exhaustion that leads to a human "
              f"wait names its counter in `{lc.PENDING_COUNTER}`, and the resume from that wait "
              "starts exactly that counter again, and no other.", "",
              "| Budget | One charge | Counter | Limit | Infrastructure | Charged by | Exhaustion |",
              "|:-------|:-----------|:--------|:------|:---------------|:-----------|:-----------|"]
    for name, b in lc.BUDGETS.items():
        value = lc.budget_limit(name, policy) - b.offset
        limit = f"`{b.policy_key}` ({value})"
        if b.offset:
            limit = f"{b.offset} + {limit} = {value + b.offset}"
        charged = sorted({f"`{e.verb}` from `{e.source}`" for e in lc.table_edges()
                          if name in e.transition.charges})
        exhaustion = [f"`{e.verb}`: `{e.source}` to `{e.target}`" for e in lc.exhaustion_edges(name)]
        lines.append(f"| `{name}` | {cell(b.unit)} | {cell(b.counter)} | {limit} | "
                     f"{'yes' if b.infrastructure else 'no'} | {'; '.join(charged)} | "
                     f"{'; '.join(exhaustion)} |")
    lines += ["", "Two more limits are read from `policy.json`: "
              f"`{lc.STALE_KEY}` ({lc.policy_value(policy, lc.STALE_KEY)}) is the length of a stop "
              "after which `resume_stale` applies, and "
              f"`{lc.REMINDER_KEY}` ({lc.policy_value(policy, lc.REMINDER_KEY)}) is the interval of "
              "`record_reminder`.", ""]
    title, text = lc.OPERATION_SECTION
    lines += ["## Operation table", "", text, "",
              f"An operation starts in `{lc.OPERATION_INITIAL_STATE}` "
              f"(`{lc.OPERATION_INITIAL_VERB}`).", "",
              "| State | Open | Exits | Description |", "|:------|:-----|:------|:------------|"]
    for key, s in lc.OPERATIONS.items():
        lines.append(f"| `{key}` | {'yes' if s.open else 'no'} | {len(s.transitions)} | "
                     f"{cell(s.description)} |")
    lines.append("")
    for key, s in lc.OPERATIONS.items():
        lines += [f"### Operation `{key}`", f"{{: #operation-{key} }}", ""]
        if not s.transitions:
            lines += ["End state: no transition leaves it.", ""]
            continue
        lines += TRANSITION_HEADER
        for e in lc.table_edges({key: s}):
            to = "same state" if e.target == key else f"`{e.target}`"
            lines.append(transition_row(e.verb, to, e.transition))
        lines.append("")
    return "\n".join(lines)


def item_lines(heading: str, d: Item, label: str) -> list[str]:
    lines = [f"### {heading}", "", d.question, "", f"**{label}.** {d.text}", ""]
    if d.options:
        lines += [f"- **{letter}.** {text}" for letter, text in d.options] + [""]
    return lines + [item_markdown(d), ""]


def render_decisions() -> str:
    lines = front_matter("Decisions", 2, "/state-machine/decisions/", parent=True)
    lines += [
        "# Decisions", "{: .no_toc }", "",
        "This page records the decisions behind the " + TABLE_LINK + ". The open items come "
        "first: each is a question that is not settled, and until it is, the table entry it "
        "names is the working definition. The settled decisions follow, each with the slice of "
        "the table that now holds it. Items keep their number when they are settled, so the "
        "open items are numbered after the settled ones. Each diagram shows only the states and verbs involved: "
        "thick arrows are the table transitions the item is about, dashed arrows are transitions "
        "an option of an open item would add (labelled with the option), and a node with a "
        "dashed border is a state the table does not have.", "",
    ]
    lines += toc()
    lines += ["## Rules behind the decisions", ""]
    lines += [f"{n}. {text}" for n, text in enumerate(RULES_BEHIND, 1)]
    lines += ["", "## Open items", ""]
    if not OPEN_ITEMS:
        lines += ["No item is open.", ""]
    for number, d in enumerate(OPEN_ITEMS, len(SETTLED_OPEN_ITEMS) + 1):
        lines += item_lines(f"O{number}. {d.title}", d, "Table")
    lines += ["## Settled decisions", ""]
    for number, d in enumerate(DECISIONS, 1):
        lines += item_lines(f"{number}. {d.title}", d, "Decision")
    lines += ["## Settled open items", ""]
    for number, d in enumerate(SETTLED_OPEN_ITEMS, 1):
        lines += item_lines(f"O{number}. {d.title}", d, "Decision")
    lines += ["## Further settled changes", ""]
    for d in FURTHER_CHANGES:
        lines += item_lines(d.title, d, "Change")
    return "\n".join(lines)


CONTRIBUTION_SCHEMA = Path("schemas/contribution.schema.json")


def contribution_schema(committed: dict) -> str:
    """The contribution record schema with the parts the table defines: the
    `phase` and `activity` enums are the phases and activities of the
    table's states, the counter a pending human action names is a budget of
    the table, and every property of the record is required but the
    optional ones (``engine.OPTIONAL_RECORD_FIELDS``), which no record is
    migrated for."""
    schema = json.loads(json.dumps(committed))
    props = schema["properties"]
    for name, values in (("phase", lc.PHASES), ("activity", lc.ACTIVITIES)):
        props[name] = {"enum": list(values)}
    pending = next(branch for branch in props["pending_human_action"]["anyOf"]
                   if branch.get("type") == "object")
    pending["properties"]["counter"] = {"enum": [*lc.BUDGETS, None]}
    schema["required"] = [name for name in props if name not in engine.OPTIONAL_RECORD_FIELDS]
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def render(policy: dict) -> dict[Path, str]:
    return {
        OUT / "index.md": render_index(),
        OUT / "table.md": render_table(policy),
        OUT / "decisions.md": render_decisions(),
        CONTRIBUTION_SCHEMA: contribution_schema(
            json.loads((ROOT / CONTRIBUTION_SCHEMA).read_text())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when committed pages differ")
    args = parser.parse_args()
    policy = json.loads((ROOT / "policy.json").read_text())
    stale = []
    for path, text in render(policy).items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
    if stale:
        print("stale generated pages: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
