"""Generate docs/state-machine/ from the lifecycle table in lifecycle.py.

Run from the repository root:

    uv run --locked python -m scripts.generate_state_machine_doc

``--check`` exits non-zero when a committed page differs from the table.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import lifecycle as lc
from scripts.state_machine_decisions import DECISIONS, Decision

ROOT = Path(lc.__file__).resolve().parent
OUT = Path("docs/state-machine")
GENERATED = ("<!-- Generated by scripts/generate_state_machine_doc.py from the lifecycle table "
             "in lifecycle.py. Do not edit; change the table and regenerate. -->")
TABLE_LINK = "[lifecycle table]({{ '/state-machine/table/' | relative_url }})"
DECISIONS_LINK = "[open decisions]({{ '/state-machine/decisions/' | relative_url }})"


# --------------------------------------------------------------------------
# Mermaid


def node_id(node: str) -> str:
    state, _, flag = node.partition("+")
    phase, activity = state.split(".", 1)
    base = f"{lc.DIAGRAM_PHASE_IDS.get(phase, phase)}_{activity}"
    return f"{base}_{flag}" if flag else base


def node_label(node: str) -> str:
    state, _, flag = node.partition("+")
    return f"{state}, {flag}=true" if flag else state


def edge_label(verb: str, t: lc.Transition) -> str:
    return f"{verb}<br/>{t.command}" if t.command else verb


def flowchart(nodes, edges, *, start=None, start_label=None, ends=(), proposed=()) -> str:
    """``edges``: ``(source, label, target, arrow)`` with arrow ``-->``, ``==>`` or ``-.->``."""
    lines = ["```mermaid", "flowchart TB"]
    groups: dict[str, list[str]] = {}
    for node in nodes:
        groups.setdefault(node.split(".", 1)[0], []).append(node)
    for phase, members in groups.items():
        lines.append(f'    subgraph {phase}["{phase}"]')
        for node in members:
            suffix = ":::proposed" if node in proposed else ""
            lines.append(f'        {node_id(node)}["{node_label(node)}"]{suffix}')
        lines.append("    end")
    lines.append("")
    n = 0
    if start:
        n += 1
        arrow = f"-->|{start_label}|" if start_label else "-->"
        lines.append(f"    start_{n}(( )) {arrow} {node_id(start)}")
    for source, label, target, arrow in edges:
        lines.append(f"    {node_id(source)} {arrow}|{label}| {node_id(target)}")
    for node in ends:
        n += 1
        lines.append(f"    {node_id(node)} --> end_{n}(( ))")
    if proposed:
        lines.append("    classDef proposed stroke-dasharray: 5 5")
    lines.append("```")
    return "\n".join(lines)


def flag_flowchart(state: str, flag: str) -> str:
    f = lc.FLAGS[flag]
    return "\n".join([
        "```mermaid", "flowchart TB",
        f'    active["{state}"]',
        f'    {flag}["{node_label(state + "+" + flag)}"]',
        "",
        "    start_1(( )) --> active",
        f"    active -->|{edge_label(f.set_verb, f.set_by)}| {flag}",
        f"    {flag} -->|{edge_label(f.clear_verb, f.cleared_by)}| active",
        "```",
    ])


def diagram_markdown(d: lc.Diagram) -> str:
    if d.flags:
        return "\n\n".join(flag_flowchart(d.nodes[0], flag) for flag in d.flags)
    edges = []
    for source, verb in d.edges:
        t, target = lc.resolve_node(source, verb)
        edges.append((source, edge_label(verb, t), target, "-->"))
    return flowchart(d.nodes, edges, start=d.start, start_label=d.start_verb, ends=d.ends)


def decision_markdown(d: Decision) -> str:
    edges = []
    for source, verb in d.edges:
        t, target = lc.resolve_node(source, verb)
        arrow = "==>" if (source, verb) in d.contested else "-->"
        edges.append((source, edge_label(verb, t), target, arrow))
    for c in d.candidates:
        edges.append((c.source, f'"{c.option}: {c.label}"', c.target, "-.->"))
    proposed = tuple(n for n in d.nodes if n.partition("+")[0] not in lc.LIFECYCLE)
    return flowchart(d.nodes, edges, proposed=proposed)


# --------------------------------------------------------------------------
# Tables


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def code(names) -> str:
    return ", ".join(f"`{n}`" for n in names)


def effects_text(e: lc.Effects) -> str:
    parts = []
    if e.revision == "bump":
        parts.append("revision +1")
    if e.generation == "bump":
        parts.append("generation +1")
    if e.work != "keep":
        parts.append(f"Work: {e.work}")
    if e.sets:
        parts.append(f"sets {code(e.sets)}")
    if e.clears:
        parts.append(f"clears {code(e.clears)}")
    return "; ".join(parts) or "none"


def trigger_text(t: lc.Transition) -> str:
    return f"{t.trigger} (`{t.command}`)" if t.command else str(t.trigger)


def front_matter(title: str, nav_order: int, permalink: str, *, parent: bool = False,
                 children: bool = False) -> list[str]:
    lines = ["---", f"title: {title}"]
    if parent:
        lines.append("parent: State machine")
    lines.append(f"nav_order: {nav_order}")
    if children:
        lines.append("has_children: true")
    lines += [f"permalink: {permalink}", "---", "", GENERATED, ""]
    return lines


def toc() -> list[str]:
    return ["<details open markdown=\"block\">", "  <summary>Contents</summary>",
            "  {: .text-delta }", "1. TOC", "{:toc}", "</details>", ""]


def render_index() -> str:
    lines = front_matter("State machine", 7, "/state-machine/", children=True)
    lines += [
        "# Contribution state machine", "{: .no_toc }", "",
        "The contribution lifecycle is defined by one table in `lifecycle.py`. That table is the "
        "source of truth: every diagram on this page, the " + TABLE_LINK + " reference, and the "
        + DECISIONS_LINK + " page are generated from it by `scripts/generate_state_machine_doc.py`, "
        "and a test fails when a page no longer matches the table.", "",
        "`uv run --locked python -m lifecycle check` verifies that the table is consistent, and "
        "the Agent Validation workflow runs it on every pull request and every push to `main`. "
        "It checks that every target exists, every state is reachable from "
        f"`{lc.INITIAL_STATE}`, and an end state (kind `terminal`) is reachable from every state; "
        "that end states have no exits and every other state has one that leaves it; that every "
        "transition names its trigger and its guard (`always` when unconditional), every command "
        "transition its command and the revision it accepts, and every charged budget a "
        "`policy.json` key and an exhaustion transition; that a verb leads from a state to one "
        "target only; that revision bumps follow the revision rule; and that every "
        "state, transition, and flag is drawn below and every decision slice uses table "
        "entries.", "",
        "A state is `phase.activity`. Each arrow is a transition verb of the table, labelled with "
        "its `/upstreaming` command when a command triggers it; the other transitions are taken "
        "on a Result, an observation, an operation receipt, or a controller tick, as the table "
        "records.", "",
    ]
    lines += toc()
    for section in lc.DIAGRAM_SECTIONS:
        lines += [f"## {section.title}", "", section.text, ""]
        for d in section.diagrams:
            if d.title:
                lines += [f"### {d.title}", ""]
            lines += [diagram_markdown(d), ""]
            if d.text:
                lines += [d.text, ""]
    lines += ["## Command impact summary", "",
              "Every `/upstreaming` command that the table accepts, with the transitions it "
              "triggers.", "",
              "| Command | Verb | From | To |", "|:--------|:-----|:-----|:---|"]
    rows: dict[tuple[str, str, str], list[str]] = {}
    for e in lc.table_edges():
        if e.transition.command:
            rows.setdefault((e.transition.command, e.verb, e.target), []).append(e.source)
    for flag in lc.FLAGS.values():
        for verb, t in ((flag.set_verb, flag.set_by), (flag.clear_verb, flag.cleared_by)):
            rows.setdefault((t.command, verb, "same state"), []).append("every non-terminal state")
    for (command, verb, target), sources in sorted(rows.items()):
        to = target if target == "same state" else f"`{target}`"
        frm = sources[0] if sources == ["every non-terminal state"] else code(sources)
        lines.append(f"| `{command}` | `{verb}` | {frm} | {to} |")
    lines.append("")
    return "\n".join(lines)


def render_table(policy: dict) -> str:
    lines = front_matter("Lifecycle table", 1, "/state-machine/table/", parent=True)
    states = len(lc.LIFECYCLE)
    rows = sum(len(s.transitions) for s in lc.LIFECYCLE.values())
    verbs = len({e.verb for e in lc.table_edges()})
    lines += [
        "# Lifecycle table", "{: .no_toc }", "",
        "This is the contribution state machine as defined in `lifecycle.py`: "
        f"{states} states, {rows} transitions with {verbs} distinct verbs, {len(lc.FLAGS)} flags, "
        f"and {len(lc.BUDGETS)} retry budgets. A contribution starts in `{lc.INITIAL_STATE}` "
        f"(`{lc.INITIAL_VERB}`).", "",
    ]
    lines += toc()
    lines += ["## Triggers", "", "| Trigger | Meaning |", "|:--------|:--------|"]
    lines += [f"| `{k}` | {cell(v)} |" for k, v in lc.TRIGGER_DESCRIPTIONS.items()]
    lines += ["", "## State kinds", "", "| Kind | Meaning |", "|:-----|:--------|"]
    lines += [f"| `{k}` | {cell(v)} |" for k, v in lc.KIND_DESCRIPTIONS.items()]
    lines += ["", "## States", "",
              "*Launches* means the controller may allocate Work or launch remote effects from the "
              "state, subject to the flags. *Fork writes* means automated writers may write the "
              "contribution fork.", "",
              "| State | Kind | Launches | Fork writes | Exits | Description |",
              "|:------|:-----|:---------|:------------|:------|:------------|"]
    for key, s in lc.LIFECYCLE.items():
        exits = len(s.transitions)
        lines.append(f"| `{key}` | `{s.kind}` | {'yes' if s.launches else 'no'} | "
                     f"{'yes' if s.writes else 'no'} | {exits} | {cell(s.description)} |")
    lines += ["", "## Flags", "",
              "Flags are stored beside the state and do not change phase or activity. They are "
              "set and cleared from every non-terminal state.", ""]
    for name, f in lc.FLAGS.items():
        lines += [f"### `{name}`", "", f"Stored in `{f.field}`. {f.description}", "",
                  "| Verb | Trigger | Guard | Effects |", "|:-----|:--------|:------|:--------|"]
        for verb, t in ((f.set_verb, f.set_by), (f.clear_verb, f.cleared_by)):
            lines.append(f"| `{verb}` | {trigger_text(t)} | {cell('; '.join(t.guard))} | "
                         f"{effects_text(t.effects)} |")
        lines += ["", "While set:", "", "| Trigger | Effect |", "|:--------|:-------|"]
        lines += [f"| `{k}` | {cell(v)} |" for k, v in f.mask.items()]
        lines.append("")
    lines += ["## Transitions", "",
              "For each state, the verbs available from it. A verb leads from a state to one "
              "target only. *Same state* means the transition keeps phase and activity.", ""]
    for key, state in lc.LIFECYCLE.items():
        lines += [f"### `{key}`", ""]
        if not state.transitions:
            lines += ["Terminal: no transition leaves this state.", ""]
            continue
        lines += ["| Verb | Trigger | To | Guard | Effects | Charges |",
                  "|:-----|:--------|:---|:------|:--------|:--------|"]
        for (verb, to), t in state.transitions.items():
            to = "same state" if to == lc.SELF else f"`{to}`"
            guard = "; ".join(t.guard)
            if t.description:
                guard = f"{guard}. {t.description}" if guard else t.description
            lines.append(f"| `{verb}` | {trigger_text(t)} | {to} | {cell(guard)} | "
                         f"{effects_text(t.effects)} | {code(t.charges) or '-'} |")
        lines.append("")
    lines += ["## Budgets", "",
              "Each budget counts charges by the verbs that name it. Its limit is a `policy.json` "
              "value, plus one when the first try is free. When the count reaches the limit, the "
              "exhaustion verb is taken instead.", "",
              "| Budget | One charge | Counter | Limit | Charged by | Exhaustion |",
              "|:-------|:-----------|:--------|:------|:-----------|:-----------|"]
    for name, b in lc.BUDGETS.items():
        value = lc.budget_limit(name, policy) - b.offset
        limit = f"`{b.policy_key}` ({value})"
        if b.offset:
            limit = f"{b.offset} + {limit} = {value + b.offset}"
        else:
            limit = f"{limit}"
        charged = sorted({f"`{e.verb}` from `{e.source}`" for e in lc.table_edges()
                          if name in e.transition.charges})
        exhaustion = sorted({f"`{e.source}` to `{e.target}`" for e in lc.exhaustion_edges(name)})
        lines.append(f"| `{name}` | {cell(b.unit)} | {cell(b.counter)} | {limit} | "
                     f"{'; '.join(charged)} | `{b.exhaustion_verb}`: {'; '.join(exhaustion)} |")
    lines.append("")
    return "\n".join(lines)


def render_decisions() -> str:
    lines = front_matter("Open decisions", 2, "/state-machine/decisions/", parent=True)
    lines += [
        "# Open decisions", "{: .no_toc }", "",
        "Each item is a question about the " + TABLE_LINK + " that is not settled. Until it is, "
        "the table entry the item names is the working definition. Each diagram shows only the "
        "states and verbs involved: thick arrows are the table transitions in question, dashed "
        "arrows are transitions an option would add (labelled with the option), and a node with "
        "a dashed border is a state the table does not have.", "",
    ]
    lines += toc()
    for number, d in enumerate(DECISIONS, 1):
        lines += [f"## {number}. {d.title}", "", d.question, "", f"**Table.** {d.table}", ""]
        lines += [f"- **{letter}.** {text}" for letter, text in d.options]
        lines += ["", decision_markdown(d), ""]
    return "\n".join(lines)


def render(policy: dict) -> dict[Path, str]:
    return {
        OUT / "index.md": render_index(),
        OUT / "table.md": render_table(policy),
        OUT / "decisions.md": render_decisions(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when committed pages differ")
    args = parser.parse_args()
    policy = json.loads((ROOT / "policy.json").read_text())
    stale = []
    for path, text in render(policy).items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
    if stale:
        print("stale generated pages: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
